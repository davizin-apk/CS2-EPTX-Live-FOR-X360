"""Preflight the design sheets and generate scripts/gen/defs.gd from them."""
import json, glob, os, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sheets = {}
for fn in sorted(glob.glob(os.path.join(root, 'design', '*.json'))):
    s = json.load(open(fn, encoding='utf-8'))
    sheets[s['sheet']] = s
problems = []
BLANK_OK = {('assets', 'anims'), ('assets', 'out')}
for name, s in sheets.items():
    ids = set()
    for r in s['rows']:
        if r.get('id') in ids: problems.append(f"{name}: duplicate id {r.get('id')}")
        ids.add(r.get('id'))
        for c in s['columns']:
            if c not in r: problems.append(f"{name}.{r.get('id')}.{c}: missing"); continue
            if r[c] in ('', None) and (name, c) not in BLANK_OK: problems.append(f"{name}.{r.get('id')}.{c}: empty")
        for c in r:
            if c not in s['columns']: problems.append(f"{name}.{r.get('id')}.{c}: not a column")
def ids(n): return {r['id'] for r in sheets[n]['rows']}
refs = [('weapons','model_asset','assets'),('weapons','icon_asset','assets'),('weapons','sound_asset','assets'),
        ('equipment','icon_asset','assets'),('teams','agent_asset','assets'),('teams','default_pistol','weapons'),
        ('maps','map_asset','assets'),('maps','phys_asset','assets'),('maps','ents_asset','assets'),('maps','trig_asset','assets'),('modes','map','maps')]
refs.append(('weapons','shell_asset','assets'))
refs.append(('weapons','only_mode','modes'))
refs += [('modes','ruleset','rulesets'),('weapons16','weapon','weapons')]
missing16 = ids('weapons') - {r['weapon'] for r in sheets['weapons16']['rows']}
if missing16: problems.append(f'weapons16: no 1.6 row for {sorted(missing16)}')
for sh, col, target in refs:
    for r in sheets[sh]['rows']:
        if r[col] not in ('none', 'any') and r[col] not in ids(target): problems.append(f"{sh}.{r['id']}.{col}: '{r[col]}' not in {target}")
for r in sheets['systems']['rows']:
    if not os.path.exists(os.path.join(root, r['script'])): problems.append(f"systems.{r['id']}.script: {r['script']} not written yet")
    for sh in r['reads_sheets'].split(','):
        if sh not in sheets: problems.append(f"systems.{r['id']}.reads_sheets: no sheet {sh}")
for r in sheets['assets']['rows']:
    if r['kind'] != 'file' and not r['out']: problems.append(f"assets.{r['id']}.out: empty")
    if r['kind'] == 'model' and r['id'].startswith('mdl_') and r['id'] in ('mdl_ct','mdl_t') and not r['anims']: problems.append(f"assets.{r['id']}.anims: agent needs anims")
def gd(v):
    if isinstance(v, bool): return 'true' if v else 'false'
    if isinstance(v, (int, float)): return repr(v)
    if isinstance(v, list): return '[' + ', '.join(gd(x) for x in v) + ']'
    return json.dumps(v)
out = ['# Generated by tools/preflight.py from design/*.json. Do not edit by hand.', 'extends RefCounted', '']
for name, s in sheets.items():
    out.append(f'const {name.upper()} := {{')
    for r in s['rows']:
        out.append(f'\t{json.dumps(r["id"])}: {{' + ', '.join(f'{json.dumps(c)}: {gd(r[c])}' for c in s['columns'] if c in r) + '},')
    out.append('}'); out.append('')
os.makedirs(os.path.join(root, 'scripts', 'gen'), exist_ok=True)
open(os.path.join(root, 'scripts', 'gen', 'defs.gd'), 'w', encoding='utf-8').write('\n'.join(out))
print(f"{sum(len(s['rows']) for s in sheets.values())} rows in {len(sheets)} sheets")
print('\n'.join(problems) if problems else 'PREFLIGHT CLEAN')
sys.exit(1 if problems else 0)
